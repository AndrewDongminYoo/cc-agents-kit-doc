import assert from "node:assert/strict"
import { spawnSync } from "node:child_process"
import { createHash } from "node:crypto"
import { copyFile, mkdtemp, readFile, rm, writeFile } from "node:fs/promises"
import { tmpdir } from "node:os"
import path from "node:path"
import { fileURLToPath, pathToFileURL } from "node:url"

import ts from "typescript"

const projectRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  ".."
)
const dataUrl = (code) =>
  `data:text/javascript;base64,${Buffer.from(code).toString("base64")}`

async function compile(relativePath) {
  return ts.transpileModule(
    await readFile(path.join(projectRoot, relativePath), "utf8"),
    {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2023,
      },
    }
  ).outputText
}

export async function readInventory() {
  const examples = dataUrl(await compile("src/tool-examples.ts"))
  const content = await compile("src/content.ts")
  assert.equal(
    content.split('"./tool-examples"').length,
    2,
    "The content module's tool-examples import changed."
  )
  const { release } = await import(
    dataUrl(content.replace('"./tool-examples"', JSON.stringify(examples)))
  )
  return release
}

export function renderSvg(template, mark, inventory) {
  assert.doesNotMatch(
    mark,
    /<text\b|font-family|@font-face/,
    "The shared brand mark must use fixed outlines."
  )
  const circle = mark.match(/<circle\b[^>]*\/>/)?.[0]
  const lettering = mark.match(/<g\b[^>]*>[\s\S]*<\/g>/)?.[0]
  assert.ok(
    circle && lettering,
    "The shared brand mark's circle or lettering is missing."
  )
  const values = {
    header_mark: `<g transform="translate(74 77) scale(1.0625)">${circle}${lettering}</g>`,
    hook_count: String(inventory.hookCount).padStart(2, "0"),
    illustration_mark: `<g transform="translate(71 71) scale(2.5)">${lettering}</g>`,
    mod_count: String(inventory.modCount).padStart(2, "0"),
    plugin_count: String(inventory.pluginCount).padStart(2, "0"),
    skill_count: String(inventory.skillCount).padStart(2, "0"),
  }
  const svg = template.replace(/\$\{([a-z_]+)\}/g, (_, key) => {
    assert.ok(Object.hasOwn(values, key), `Unknown OG template field: ${key}`)
    return values[key]
  })
  assert.doesNotMatch(svg, /\$\{/, "An OG template field was left unresolved.")
  return `<!-- Generated by tools/generate-og-image.mjs; edit tools/og-image.svg.template. -->\n${svg}`
}

function browser(command, args, options = {}) {
  const result = spawnSync("agent-browser", [...command, ...args], {
    cwd: projectRoot,
    stdio: "inherit",
    timeout: 60000,
    ...options,
  })
  if (result.error) throw result.error
  assert.equal(result.status, 0, `agent-browser ${args[0]} failed.`)
}

export function verifyPngDimensions(png) {
  assert.ok(png.length >= 24, "The PNG header is incomplete.")
  assert.equal(
    png.subarray(0, 8).toString("hex"),
    "89504e470d0a1a0a",
    "The PNG signature is invalid."
  )
  assert.equal(
    png.toString("ascii", 12, 16),
    "IHDR",
    "The PNG dimensions header is missing."
  )
  assert.equal(png.readUInt32BE(16), 1200, "The PNG width must be 1200 pixels.")
  assert.equal(png.readUInt32BE(20), 630, "The PNG height must be 630 pixels.")
}

export function verifyImageProvenance(svg, png, provenance) {
  assert.equal(provenance.schemaVersion, 1, "Unknown OG provenance schema.")
  assert.equal(
    createHash("sha256").update(svg).digest("hex"),
    provenance.svgSha256,
    "The OG SVG changed after its PNG export; regenerate both images."
  )
  assert.equal(
    createHash("sha256").update(png).digest("hex"),
    provenance.pngSha256,
    "The OG PNG does not match its recorded export; regenerate both images."
  )
}

async function main() {
  const args = process.argv.slice(2)
  const svgOnly = args.includes("--svg-only")
  assert.ok(
    args.every((argument) => argument === "--svg-only"),
    "Usage: node tools/generate-og-image.mjs [--svg-only]"
  )
  const [inventory, template, mark] = await Promise.all([
    readInventory(),
    readFile(path.join(projectRoot, "tools/og-image.svg.template"), "utf8"),
    readFile(path.join(projectRoot, "public/favicon.svg"), "utf8"),
  ])
  const svg = renderSvg(template, mark, inventory)
  const destination = path.join(projectRoot, "public")
  if (svgOnly) {
    await writeFile(path.join(destination, "og-image.svg"), svg)
    process.stdout.write(`Generated OG SVG for v${inventory.version}.\n`)
    return
  }

  const temporaryDirectory = await mkdtemp(path.join(tmpdir(), "cc-kit-og-"))
  const command = [
    "--namespace",
    `cc-kit-og-${process.pid}`,
    "--session",
    "export",
  ]
  const temporarySvg = path.join(temporaryDirectory, "og-image.svg")
  const temporaryPng = path.join(temporaryDirectory, "og-image.png")
  try {
    await writeFile(temporarySvg, svg)
    browser(command, ["open", pathToFileURL(temporarySvg).href])
    browser(command, ["set", "viewport", "1200", "630", "1"])
    browser(command, ["wait", "--fn", 'document.fonts.status === "loaded"'])
    browser(command, ["screenshot", temporaryPng])
    const png = await readFile(temporaryPng)
    verifyPngDimensions(png)
    await writeFile(path.join(destination, "og-image.svg"), svg)
    await copyFile(temporaryPng, path.join(destination, "og-image.png"))
    await writeFile(
      path.join(destination, "og-image.provenance.json"),
      `${JSON.stringify(
        {
          pngSha256: createHash("sha256").update(png).digest("hex"),
          schemaVersion: 1,
          svgSha256: createHash("sha256").update(svg).digest("hex"),
        },
        null,
        2
      )}\n`
    )
    process.stdout.write(
      `Generated OG SVG and 1200×630 PNG for v${inventory.version}.\n`
    )
  } finally {
    try {
      browser(command, ["close"], { timeout: 10000 })
    } finally {
      await rm(temporaryDirectory, { recursive: true })
    }
  }
}

if (
  process.argv[1] &&
  path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  await main()
}
